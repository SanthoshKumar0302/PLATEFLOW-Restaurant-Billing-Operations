export const DEFAULT_HOTEL_LOCATION = {
  address: '124 Culinary Blvd',
  state: 'Tamil Nadu',
  city: 'Chennai',
  pincode: '600123',
};

export const getSavedHotelLocation = () => {
  try {
    const saved = localStorage.getItem('plateflow-hotel-location');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (parsed?.city && parsed?.pincode) return parsed;
    }
  } catch {
    /* fallback to default */
  }
  return DEFAULT_HOTEL_LOCATION;
};

export const formatHotelAddress = (location = DEFAULT_HOTEL_LOCATION) => {
  const address = location.address || '124 Culinary Blvd';
  const city = location.city || 'Chennai';
  const state = location.state || 'Tamil Nadu';
  const pincode = location.pincode || '600123';
  return `${address}, ${city}, ${state} - ${pincode}`;
};
